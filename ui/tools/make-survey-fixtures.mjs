// GeoJSON (WGS84): inverse UTM 48N for the test file
function utmInv(E, N, zone = 48) {
  const a = 6378137, f = 1 / 298.257223563, k0 = 0.9996, n = f / (2 - f), A = (a / (1 + n)) * (1 + n * n / 4 + n ** 4 / 64)
  const be = [n / 2 - (2 / 3) * n * n + (37 / 96) * n ** 3, n * n / 48 + n ** 3 / 15, (17 / 480) * n ** 3]
  const de = [2 * n - (2 / 3) * n * n - 2 * n ** 3, (7 / 3) * n * n - (8 / 5) * n ** 3, (56 / 15) * n ** 3]
  const xi = N / (k0 * A), eta = (E - 500000) / (k0 * A)
  let xp = xi, ep = eta
  for (let j = 1; j <= 3; j++) { xp -= be[j - 1] * Math.sin(2 * j * xi) * Math.cosh(2 * j * eta); ep -= be[j - 1] * Math.cos(2 * j * xi) * Math.sinh(2 * j * eta) }
  const chi = Math.asin(Math.sin(xp) / Math.cosh(ep))
  let phi = chi; for (let j = 1; j <= 3; j++) phi += de[j - 1] * Math.sin(2 * j * chi)
  return [zone * 6 - 183 + (Math.atan(Math.sinh(ep) / Math.cos(xp)) * 180) / Math.PI, (phi * 180) / Math.PI]
}
