function shpFile(type, records) {
  // records: array of ArrayBuffer contents (incl. shape type)
  const total = 100 + records.reduce((a, r) => a + 8 + r.byteLength, 0)
  const b = new ArrayBuffer(total), v = new DataView(b)
  v.setInt32(0, 9994, false); v.setInt32(24, total / 2, false); v.setInt32(28, 1000, true); v.setInt32(32, type, true)
  let o = 100
  records.forEach((r, i) => { v.setInt32(o, i + 1, false); v.setInt32(o + 4, r.byteLength / 2, false); new Uint8Array(b, o + 8).set(new Uint8Array(r)); o += 8 + r.byteLength })
  return Buffer.from(b)
}
function dbfFile(fields, rows) {
  const headerLen = 32 + fields.length * 32 + 1, recLen = 1 + fields.reduce((a, f) => a + f.len, 0)
  const b = Buffer.alloc(headerLen + rows.length * recLen + 1, 0x20)
  b.writeUInt8(3, 0); b.writeUInt32LE(rows.length, 4); b.writeUInt16LE(headerLen, 8); b.writeUInt16LE(recLen, 10)
  b.fill(0, 12, 32)
  fields.forEach((f, i) => { const o = 32 + i * 32; b.fill(0, o, o + 32); b.write(f.name, o, 'ascii'); b.write(f.type, o + 11, 'ascii'); b.writeUInt8(f.len, o + 16); b.writeUInt8(f.dec ?? 0, o + 17) })
  b.writeUInt8(0x0d, headerLen - 1)
  rows.forEach((r, j) => { let o = headerLen + j * recLen; b.write(' ', o++); fields.forEach((f, i) => { const s = String(r[i]); b.write(f.type === 'N' ? s.padStart(f.len) : s.padEnd(f.len), o, 'ascii'); o += f.len }) })
  b.writeUInt8(0x1a, b.length - 1)
  return b
}
