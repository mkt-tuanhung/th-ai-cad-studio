export function blockerText(code: string, t: typeof cncEn): string {
  const i = code.indexOf(':')
  const key = i < 0 ? code : code.slice(0, i)
  const detail = i < 0 ? '' : code.slice(i + 1)
  return `${key} — ${t.blocker[key] ?? key}${detail ? ` (${detail})` : ''}`
}
